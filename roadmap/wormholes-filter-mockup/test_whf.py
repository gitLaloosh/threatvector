"""Clicks through the Wormholes filter mockup at 1440 and 390 px.  python3 -I test_whf.py wormholes_filter_mockup.html shots_f/"""
import os, sys, time
from playwright.sync_api import sync_playwright
page_path, out = os.path.abspath(sys.argv[1]), sys.argv[2]
os.makedirs(out, exist_ok=True)
fails = []
def ok(c, what):
    print(('ok   ' if c else 'FAIL ') + what)
    if not c: fails.append(what)
with sync_playwright() as p:
    b = p.chromium.launch()
    for W, H in ((1440, 1000), (390, 844)):
        ctx = b.new_context(viewport={'width': W, 'height': H}, bypass_csp=True, device_scale_factor=1)
        pg = ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto('file://' + page_path)
        pg.wait_for_function('window.__MKREADY || window.__MKERR', timeout=30000)
        ok(not pg.evaluate('window.__MKERR'), f'{W}: boot')
        time.sleep(3.5)
        side = lambda: pg.evaluate('document.scrollingElement.scrollWidth <= innerWidth + 1')
        top = lambda: pg.evaluate("document.querySelector('.it-top') && document.querySelector('.it-top').scrollIntoView({block: 'start'})")
        ok(pg.evaluate('document.querySelectorAll("[data-im-f]").length') == 6 and pg.evaluate('!!document.querySelector("[data-im-f=wh]")'), f'{W}: six filters, Wormholes last')
        ok(pg.evaluate('document.querySelectorAll(".it-gtag.whf").length') >= 2, f'{W}: Wormhole badges in Intel (Near You / Feed)')
        pg.locator('#intelPanel .it-gear').first.click(); time.sleep(1.5)
        ok(pg.evaluate('!!document.querySelector("[data-whf-keep]")'), f'{W}: "keep wormhole reports for" beside "forget reports after"')
        pg.evaluate("document.querySelector('[data-whf-keep]') && document.querySelector('[data-whf-keep]').scrollIntoView({block: 'center'})"); time.sleep(.3)
        pg.screenshot(path=f'{out}/{W}_0_settings.png')
        pg.locator('#intelPanel .it-gear').first.click(); time.sleep(.5)
        ok(pg.evaluate('WHF.count()') == 6, f'{W}: 6 wormhole reports kept (the 30 h one dropped): got %d' % pg.evaluate('WHF.count()'))
        if W < 600: pg.locator('[data-it-nv="map"]').click(); time.sleep(1)
        pg.evaluate('itMapRefresh(true)'); time.sleep(.3)
        ok(pg.evaluate('WHF.live().size') == 2, f'{W}: 2 live wormhole reports drawn on Security (RERZ-L, EUU-4N): got %d' % pg.evaluate('WHF.live().size'))
        ok('wormhole reported' in pg.evaluate('document.querySelector(".it-map-leg").textContent'), f'{W}: legend names the wormhole ring')
        top(); time.sleep(.3); pg.screenshot(path=f'{out}/{W}_1_security.png')
        if W < 600:
            pg.locator('.it-map-fcur').click(); time.sleep(.3)
        pg.locator('[data-im-f="wh"]').click(); time.sleep(.6)
        ok(pg.evaluate('itm.filter') == 'wh', f'{W}: Wormholes filter on')
        ok('Wormholes' in pg.evaluate('document.querySelector(".it-map-fl").textContent'), f'{W}: legend line names it')
        top(); time.sleep(.3); pg.screenshot(path=f'{out}/{W}_2_wh.png')
        # zoom out to the galaxy to see the far ones
        for _ in range(8):
            pg.evaluate('''(() => { const z = [...document.querySelectorAll('.it-map button')].find(b => b.textContent.trim() === '−' || b.getAttribute('aria-label') === 'Zoom out'); z && z.click(); })()''')
            time.sleep(.15)
        time.sleep(.5); top(); time.sleep(.3); pg.screenshot(path=f'{out}/{W}_3_wh_galaxy.png')
        # the list: hover reveals the button (wide); it stays while the filter is on
        if W >= 600:
            pg.locator('[data-im-f="sec"]').click(); time.sleep(.8)
            vis = lambda: pg.evaluate("getComputedStyle(document.querySelector('[data-whf-list]')).visibility")
            ok(vis() == 'hidden', f'{W}: list button hidden on another filter')
            pg.locator('[data-im-f="wh"]').hover(); time.sleep(.4)
            ok(vis() == 'visible', f'{W}: hovering Wormholes shows the list button')
            pg.mouse.move(5, 5); time.sleep(1)
            ok(vis() == 'hidden', f'{W}: it goes when the pointer leaves')
            pg.locator('[data-im-f="wh"]').click(); time.sleep(.5)
        else:
            if pg.evaluate('!document.querySelector(".it-map-fb").classList.contains("open")'): pg.locator('.it-map-fcur').click(); time.sleep(.3)
        ok(pg.evaluate("getComputedStyle(document.querySelector('[data-whf-list]')).visibility") == 'visible', f'{W}: list button shown while the filter is on')
        pg.locator('[data-whf-list]').click(); time.sleep(.5)
        ok(pg.evaluate('!document.querySelector(".whf-panel").hidden'), f'{W}: the list opens')
        n0 = pg.evaluate('document.querySelectorAll(".whf-r").length')
        pg.fill('.whf-add input[name=sys]', 'Nowhere'); pg.press('.whf-add input[name=sys]', 'Enter'); time.sleep(.3)
        ok('isn’t a system' in pg.inner_text('.whf-msg'), f'{W}: an unknown name is refused')
        pg.fill('.whf-add input[name=sys]', 'amarr'); pg.check('.whf-add input[name=dr]'); pg.click('.whf-add button[type=submit]'); time.sleep(.5)
        ok(pg.evaluate('document.querySelectorAll(".whf-r").length') == n0 + 1 and pg.evaluate('WHF.st.rep[30002187] && WHF.st.rep[30002187].src') == 'you', f'{W}: Amarr added by hand (Drifter)')
        pg.screenshot(path=f'{out}/{W}_6_list.png')
        pg.click('[data-whf-rm="30002813"]'); time.sleep(.4)
        ok(not pg.evaluate('!!WHF.st.rep[30002813]') and pg.evaluate('document.querySelectorAll(".whf-r").length') == n0, f'{W}: Tama removed')
        pg.mouse.click(5, 300 if W >= 600 else 200); time.sleep(.4)
        ok(pg.evaluate('document.querySelector(".whf-panel").hidden'), f'{W}: a press outside closes it')
        if W < 600 and pg.evaluate('!document.querySelector(".it-map-fb").classList.contains("open")'): pg.locator('.it-map-fcur').click(); time.sleep(.3)
        pg.locator('[data-whf-list]').click(); time.sleep(.4); pg.click('.whf-panel .x-close'); time.sleep(.3)
        ok(pg.evaluate('document.querySelector(".whf-panel").hidden') and pg.evaluate('document.activeElement && document.activeElement.matches("[data-whf-list], .it-map-fcur")'), f'{W}: × closes it, focus back on the list button (phone: the filter button)')
        ok(side(), f'{W}: no sideways scroll with the list')
        tip = pg.evaluate('''(() => { const i = itGraphGet().at.get(30002537); itMapTip(i, 100, 100); return itm.tip.textContent; })()''')
        print('   tip:', tip[:140]); ok('Wormhole' in tip and 'Mk Gate Watcher' in tip, f'{W}: hover names the wormhole report')
        pg.evaluate('itMapTip(-1)')
        pg.locator('[data-mk="post"]').click(); time.sleep(4)
        ok(pg.evaluate('WHF.count()') == 7, f'{W}: a new "8G-2FP wormhole" line is kept')
        if W < 600:
            pg.locator('.it-map-fcur').click(); time.sleep(.3)
        pg.locator('[data-im-f="sec"]').click(); time.sleep(.6)
        ok(pg.evaluate('WHF.live().size') == 3, f'{W}: the new 8G-2FP report drawn too')
        pg.evaluate('it.set.forget = 5; itMapRefresh(true)'); time.sleep(.3)
        ok(pg.evaluate('WHF.live().size') == 1, f'{W}: with forget 5 min only the new one stays: got %d' % pg.evaluate('WHF.live().size'))
        pg.evaluate('it.set.forget = 30; itMapRefresh(true)'); time.sleep(.3)
        top(); time.sleep(.3); pg.screenshot(path=f'{out}/{W}_4_security_whring.png')
        pg.locator('#intelPanel .it-gear').first.click(); time.sleep(1.5)
        pg.evaluate("document.querySelector('[data-whf-keep]').scrollIntoView({block: 'center'})"); time.sleep(.2)
        pg.locator('[data-whf-keep]').select_option('4'); time.sleep(.6)
        ok(pg.evaluate('WHF.count()') == 5, f'{W}: keep 4 h leaves 5 (3U-48K, RERZ-L, EUU-4N, 8G-2FP, Amarr added by hand): got %d' % pg.evaluate('WHF.count()'))
        pg.screenshot(path=f'{out}/{W}_5_setting.png')
        ok(side(), f'{W}: no sideways scroll')
        ok(not errs, f'{W}: no page errors {errs[:3]}')
        ctx.close()
    b.close()
print('failed:', len(fails))
