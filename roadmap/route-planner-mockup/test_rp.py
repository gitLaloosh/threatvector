    pg.mouse.click(x2, y2, button='right'); pg.wait_for_timeout(100)
    ok('menu now says Stop avoiding', 'Stop avoiding' in pg.inner_text('.rp-menu'))
    pg.mouse.click(5, 5); pg.wait_for_timeout(100); ok('a press outside closes the menu', pg.locator('.rp-menu').count() == 0)
    # Intel settings: the Routes box
    pg.locator('[data-mk="set"]').click(); pg.wait_for_timeout(400)
    ok('Intel settings has the Routes box', pg.locator('[data-rp-box]').count() == 1)
    ok('the avoid list shows 8-WYQZ', '8-WYQZ' in pg.inner_text('[data-rp-box] .rp-list'))
    ok('penalty off while Prefer shorter', pg.locator('[data-rp-set="pen"]').is_disabled())
    k0 = pg.evaluate('rp.key'); pg.locator('[data-rp-set="pref"][value="Safer"]').check(); pg.wait_for_timeout(150)
    ok('Prefer safer: saved, routes worked out again, penalty on', pg.evaluate('rp.set.pref') == 'Safer' and pg.evaluate('rpPlan(), rp.key') != k0 and not pg.locator('[data-rp-set="pen"]').is_disabled())
    pg.locator('[data-rp-box] .rp-list [data-rp-av]').first.click(); pg.wait_for_timeout(150)
    ok('× on the list stops avoiding', pg.evaluate('rp.set.list.length') == 0)
    pg.fill('.rp-add input', '8ba-ra'); pg.locator('.rp-add button').click(); pg.wait_for_timeout(150)
    ok('typed system added to the list', pg.evaluate('rp.set.list.length') == 1)
    pg.locator('[data-rp-box]').scroll_into_view_if_needed(); pg.screenshot(path=f'{SHOTS}/1440_settings.png')
    ok('1440 no sideways scroll', pg.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    ok('1440 no page errors', not errs, errs)
    ctx.close()
    # ---- keyboard: the menu from the search box (Shift+F10)
    ctx, pg, errs = page(b, 1440, 1000)
    find(pg, 'L5-UWT'); pg.locator('.rp-search input').focus(); pg.keyboard.press('Shift+F10'); pg.wait_for_timeout(100)
