"""Route planner mockup checks: python3 -I test_rp.py <route_planner_mockup.html> <shots dir>. Every case starts on a fresh page."""
import os, sys
from playwright.sync_api import sync_playwright
HTML, SHOTS = os.path.abspath(sys.argv[1]), sys.argv[2]
os.makedirs(SHOTS, exist_ok=True)
res = []
def ok(name, cond, extra=''):
    res.append((name, bool(cond))); print(('PASS ' if cond else 'FAIL ') + name + (f'  [{extra}]' if extra and not cond else ''))
POS = '(n) => { const i = itGraphGet().at.get(it.names.byLower.get(n.toLowerCase())); const r = itm.cv.getBoundingClientRect(); return [r.left + itm.Q[2*i], r.top + itm.Q[2*i+1], i]; }'
def page(b, w, h, touch=False):
    ctx = b.new_context(viewport={'width': w, 'height': h}, bypass_csp=True, has_touch=touch, is_mobile=touch)
    pg = ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('file://' + HTML); pg.wait_for_function('window.__MKREADY || window.__MKERR', timeout=40000)
    pg.wait_for_timeout(400)
    return ctx, pg, errs
def find(pg, name):   # search, pick, return its screen position
    inp = pg.locator('.rp-search input'); inp.click(); inp.fill(name[:3].lower()); pg.wait_for_timeout(150)
    sug = pg.evaluate('() => [...document.querySelectorAll("#rpSug li")].map(l => l.textContent)')
    pg.locator(f'#rpSug li[data-rp-pick]', has_text=name).first.dispatch_event('mousedown'); pg.wait_for_timeout(200)
    return sug, pg.evaluate(POS, name)
with sync_playwright() as p:
    b = p.chromium.launch()
    # ---- 1440: search, menu, both actions, warning, avoid list, settings
    ctx, pg, errs = page(b, 1440, 1000)
    ok('1440 ready, no error', pg.evaluate('window.__MKERR || ""') == '' and not errs, errs)
    sug, (x, y, i) = find(pg, 'Z0-4AR')
    ok('search suggests Z0-4AR for "z0-"', any('Z0-4AR' in s for s in sug), sug)
    ok('picking pins its route and opens its tooltip', pg.evaluate(f'itm.pinned.has(itGraphGet().ids[{i}]) && !itm.tip.hidden'))
    ok('tooltip warns it passes a flagged system', 'No route avoids all' in pg.inner_text('.it-map-tip') and 'MJ-LGH' in pg.inner_text('.it-map-tip'))
    ok('tooltip hint: right-click', 'right-click: set destination' in pg.inner_text('.it-map-tip'))
    pg.mouse.click(x, y, button='right'); pg.wait_for_timeout(150)
    items = pg.evaluate('() => [...document.querySelectorAll(".rp-menu button")].map(b => b.textContent)')
    ok('right-click opens the menu with the three items', len(items) == 3 and "EVE's route" in items[0] and "Threat Vector's route" in items[1] and 'Avoid this system' in items[2], items)
    ok('menu: focus on the first item', pg.evaluate('document.activeElement && document.activeElement.dataset.rpGo === "eve"'))
    pg.keyboard.press('ArrowDown'); ok('menu: arrow keys move', pg.evaluate('document.activeElement && document.activeElement.dataset.rpGo === "tv"'))
    pg.keyboard.press('Escape'); ok('Esc closes the menu', pg.locator('.rp-menu').count() == 0)
    pg.mouse.click(x, y, button='right'); pg.wait_for_timeout(100); pg.locator('[data-rp-go="eve"]').click(); pg.wait_for_timeout(100)
    t = pg.inner_text('.rp-toast')
    ok("EVE's route: 1 request, destination only", 'Destination set: Z0-4AR' in t and '1 request' in t and 'autopilot settings' in t, t)
    pg.mouse.click(x, y, button='right'); pg.wait_for_timeout(100); pg.locator('[data-rp-go="tv"]').click(); pg.wait_for_timeout(100)
    t = pg.inner_text('.rp-toast')
    ok("Threat Vector's route: one request per jump, the warning", '3 jumps' in t and '3 requests' in t and 'MJ-LGH' in t and pg.locator('.rp-toast.warn').count() == 1, t)
    pg.screenshot(path=f'{SHOTS}/1440_send.png')
    # a route that differs from the shortest: 0TYR-T (3 jumps by gate, the camp at 78-0R6 on the way)
    _, (x, y, i) = find(pg, '0TYR-T')
    d, L = pg.evaluate(f'[itm.D[{i}], rpPath({i}).length - 1]')
    ok('0TYR-T: jump number stays 3, the route avoids the camp', d == 3 and L > 3, (d, L))
    ok('drawn route = Threat Vector route', pg.evaluate(f'itMapRoute({i}).length') == L)
    ok('tooltip: route jumps and the shortest', f'{L} jumps' in pg.inner_text('.it-map-tip') and '(shortest 3)' in pg.inner_text('.it-map-tip'))
    pg.screenshot(path=f'{SHOTS}/1440_detour.png')
    # avoid this system: 8-WYQZ, then Z0-4AR's route changes
    _, (x2, y2, i2) = find(pg, '8-WYQZ')
    before = pg.evaluate('rpPath(itGraphGet().at.get(it.names.byLower.get("z0-4ar"))).join()')
    pg.mouse.click(x2, y2, button='right'); pg.wait_for_timeout(100); pg.locator('.rp-menu [data-rp-av]').click(); pg.wait_for_timeout(150)
    ok('Avoid this system adds it to the list', pg.evaluate(f'rp.set.list.includes(itGraphGet().ids[{i2}])'))
    after = pg.evaluate('rpPath(itGraphGet().at.get(it.names.byLower.get("z0-4ar"))).join()')
    tz = pg.evaluate('(() => { const i = itGraphGet().at.get(it.names.byLower.get("z0-4ar")); return rpWarnText(i); })()')
