    ok('the menu is inside the map box', pg.evaluate('(() => { const m = document.querySelector(".rp-menu").getBoundingClientRect(), b = itm.box.getBoundingClientRect(); return m.left >= b.left && m.right <= b.right && m.top >= b.top && m.bottom <= b.bottom; })()'))
    ctx.close()
    # ---- 390 phone: press a system, buttons in its tooltip
    ctx, pg, errs = page(b, 390, 844, touch=True)
    ok('390 ready, no error', pg.evaluate('window.__MKERR || ""') == '' and not errs, errs)
    sw = pg.evaluate('(() => { const s = document.querySelector(".rp-search input").getBoundingClientRect(), z = itm.box.querySelector(".it-map-zoom").getBoundingClientRect(), c = itm.box.querySelector(".it-map-clr").getBoundingClientRect(); return [s.top, z.bottom, s.height, s.bottom, c.top]; })()')
    ok('390 search box under the zoom buttons, 44 px, clear of the zoom row', sw[0] >= sw[1] + 4 and sw[2] >= 44 , sw)
